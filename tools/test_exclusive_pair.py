"""Differential tests for lifted 64-bit AArch64 exclusive pair instructions.

The instruction bodies are produced by the real lifter, compiled with the host
compiler, and compared with Unicorn.  The C harness also exercises the runtime
128-bit exclusive helpers under contention.
"""
import os
import platform
import struct
import subprocess
import sys
import tempfile
import time

import unicorn as uc
from unicorn import arm64_const as A

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOLS = os.path.join(ROOT, 'tools')
WORK = os.path.join(ROOT, 'build', 'totk-experiment', 'pair-tests')
DATA = 0x7200000000
CODE = 0x7210000000
PAGE = 0x1000

sys.path.insert(0, TOOLS)
from lifter import Lifter, Unsupported  # noqa: E402


def ldxp(rt, rt2, rn, acquire=False):
    return 0xC87F0000 | (0x8000 if acquire else 0) | (rt2 << 10) | (rn << 5) | rt


def stxp(rs, rt, rt2, rn, release=False):
    return 0xC8200000 | (0x8000 if release else 0) | (rs << 16) | (rt2 << 10) | (rn << 5) | rt


CLREX = 0xD5033F5F
STR_X9_X2_8 = 0xF9000449

CASES = [
    ('ldxp_stxp', [ldxp(0, 1, 2), stxp(3, 4, 5, 2)]),
    ('ldaxp_stlxp', [ldxp(0, 1, 2, True), stxp(3, 4, 5, 2, True)]),
    ('second_store_fails', [ldxp(0, 1, 2), stxp(3, 4, 5, 2), stxp(6, 7, 8, 2)]),
    ('clrex_fails', [ldxp(0, 1, 2), CLREX, stxp(3, 4, 5, 2)]),
    ('changed_high_half_fails', [ldxp(0, 1, 2), STR_X9_X2_8, stxp(3, 4, 5, 2)]),
    # Rt/Rt2 == XZR and Rn == SP are all architecturally meaningful here.
    ('xzr_sp', [ldxp(31, 1, 31), stxp(31, 31, 31, 31)]),
    # The load destination may alias its base; the store source may alias its base.
    ('load_base_result_overlap', [ldxp(2, 1, 2)]),
    ('store_base_result_overlap', [ldxp(0, 1, 2), stxp(3, 2, 5, 2)]),
]


def lift_cases():
    lifter = Lifter(CODE, 'c')
    out = ['/* generated by tools/test_exclusive_pair.py; do not edit */', '#include "cpu.h"']
    for name, words in CASES:
        out.append(f'static void pair_{name}(Cpu *c) {{')
        for i, word in enumerate(words):
            pc = CODE + 4 * i
            ins = lifter.lift(word, pc)
            if ins.kind != 'op':
                raise AssertionError(f'{name} {word:08x} lifted as {ins.kind}: {ins.code}')
            if word & 0x3F000000 == 0x08000000:
                helper = 'ldxp128' if (word >> 22) & 1 else 'stxp128'
                if helper not in ins.code:
                    raise AssertionError(f'{name} expected {helper} in lifted body: {ins.code}')
            out.append('    ' + ins.code)
        out.append('}')
    return '\n'.join(out) + '\n'


def initial_state(name):
    x = [0x1111000000000000 + i * 0x10101 for i in range(32)]
    x[2] = DATA
    x[3] = 0xFFFFFFFFFFFFFFFF
    x[4] = 0x0123456789ABCDEF
    x[5] = 0xFEDCBA9876543210
    x[6] = 0xFFFFFFFFFFFFFFFF
    x[7] = 0xAAAAAAAAAAAAAAAA
    x[8] = 0x5555555555555555
    x[9] = 0x0F1E2D3C4B5A6978
    sp = DATA
    if name == 'load_base_result_overlap':
        x[2] = DATA
    memory = struct.pack('<QQ', 0xA1A2A3A4A5A6A7A8, 0xB1B2B3B4B5B6B7B8)
    return x, sp, memory


def unicorn_run(words, x, sp, memory):
    mu = uc.Uc(uc.UC_ARCH_ARM64, uc.UC_MODE_ARM)
    mu.mem_map(CODE, PAGE)
    mu.mem_map(DATA, PAGE)
    mu.mem_write(CODE, b''.join(struct.pack('<I', w) for w in words))
    mu.mem_write(DATA, memory)
    for i in range(29):
        mu.reg_write(A.UC_ARM64_REG_X0 + i, x[i])
    mu.reg_write(A.UC_ARM64_REG_X29, x[29])
    mu.reg_write(A.UC_ARM64_REG_X30, x[30])
    mu.reg_write(A.UC_ARM64_REG_SP, sp)
    mu.emu_start(CODE, CODE + 4 * len(words), count=len(words))
    ox = [mu.reg_read(A.UC_ARM64_REG_X0 + i) for i in range(29)]
    ox += [mu.reg_read(A.UC_ARM64_REG_X29), mu.reg_read(A.UC_ARM64_REG_X30)]
    osp = mu.reg_read(A.UC_ARM64_REG_SP)
    omem = bytes(mu.mem_read(DATA, 16))
    return ox, osp, omem


def c_run(exe, index, x, sp, memory):
    payload = struct.pack('<Q32QQ16s', index, *x, sp, memory)
    p = subprocess.run([exe], input=payload, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if p.returncode:
        raise RuntimeError(f'C harness case {CASES[index][0]} failed ({p.returncode}): '
                           f'{p.stderr.decode(errors="replace")}')
    if len(p.stdout) != struct.calcsize('<32QQ16s'):
        raise RuntimeError(f'C harness returned {len(p.stdout)} bytes, expected {struct.calcsize("<32QQ16s")}')
    unpacked = struct.unpack('<32QQ16s', p.stdout)
    return list(unpacked[:31]), unpacked[32], unpacked[33]


def main():
    os.makedirs(WORK, exist_ok=True)
    generated = os.path.join(WORK, 'exclusive_pair_generated.h')
    with open(generated, 'w') as f:
        f.write(lift_cases())

    cc = os.environ.get('CC', 'clang')
    exe = os.path.join(WORK, 'test_exclusive_pair')
    flags = ['-std=c11', '-O2', '-Wall', '-Wextra', '-Werror', '-pthread']
    if platform.machine().lower() in ('amd64', 'x86_64'):
        flags.append('-march=x86-64-v3')
    cmd = [cc] + flags + ['-I' + os.path.join(ROOT, 'runtime'), '-I' + WORK,
                         os.path.join(TOOLS, 'test_exclusive_pair.c'), '-o', exe]
    t0 = time.monotonic()
    subprocess.run(cmd, check=True)
    print(f'compiled C harness in {time.monotonic() - t0:.2f}s')

    for i, (name, words) in enumerate(CASES):
        x, sp, memory = initial_state(name)
        expected = unicorn_run(words, x, sp, memory)
        actual = c_run(exe, i, x, sp, memory)
        if actual != expected:
            for label, got, want in zip(('x', 'sp', 'memory'), actual, expected):
                if got != want:
                    if label == 'x':
                        diffs = [(j, f'{a:#018x}', f'{b:#018x}') for j, (a, b) in enumerate(zip(got, want)) if a != b]
                        print(f'{name}: x register mismatches {diffs}')
                    elif label == 'memory':
                        print(f'{name}: memory C={got.hex()} Unicorn={want.hex()}')
                    else:
                        print(f'{name}: {label} C={got:#x} Unicorn={want:#x}')
            raise SystemExit(1)
        print(f'ok: {name}')

    p = subprocess.run([exe, 'stress'], text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if p.returncode:
        raise SystemExit(f'C concurrency/layout harness failed ({p.returncode}):\n{p.stdout}{p.stderr}')
    print(p.stdout.strip())
    print(f'ok: {len(CASES)} lifted instruction sequences matched Unicorn')


if __name__ == '__main__':
    main()
